#!/usr/bin/env python3
"""Builds the site. Run it through ./build.sh.

1. Turns every _pages/<slug>.<en|de>.html into /<slug>/index.html or /de/<slug>/index.html,
   with the <x-name> components from _pages/_components filled in. Pages past their expires date are removed.
   Also writes /resources/ and /de/resources/, which list every page by topic.
2. Writes those pages into sitemap.xml, llms.txt and llms-full.txt.
3. Copies styles.css into every page, so the first paint waits on nothing.
"""
import html
import json
import re
import sys
from datetime import date, timedelta
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SITE = 'https://sightlinemac.com'
PAGES = ROOT / '_pages'
LANGS = ('en', 'de')
REQUIRED = ('title', 'description', 'updated')
OPTIONAL = ('eyebrow', 'lead', 'expires', 'topic', 'image', 'image-alt')
HUB = 'resources'
HUB_SOURCE = 'build.py#resources'
SHARE_SIZE = (1200, 630)
SHARE_TAGS = (
    'rel="canonical"', 'property="og:type"', 'property="og:title"', 'property="og:description"', 'property="og:url"',
    'property="og:image"', 'property="og:image:width"', 'property="og:image:height"', 'property="og:image:alt"',
    'name="twitter:card"', 'name="twitter:image"',
)
COMPONENT_RE = re.compile(r'<x-([a-z-]+)((?:\s+[a-z-]+="[^"]*")*)\s*(?:/>|>(.*?)</x-\1>)', re.S)
MARK = '<!-- generated by build.sh from {}, edit that file instead -->'
MARK_RE = re.compile(r'<!-- generated by build\.sh from (\S+), edit that file instead -->')


def fail(message):
    sys.exit(f'build: {message}')


def read_page(path):
    name = re.fullmatch(r'([a-z0-9]+(?:-[a-z0-9]+)*)\.(en|de)\.html', path.name)
    if not name:
        fail(f'{path.name}: name it <slug>.en.html or <slug>.de.html, with a-z, 0-9 and - in the slug')
    slug, lang = name.groups()
    text = path.read_text()
    head = re.match(r'---\n(.*?)\n---\n', text, re.S)
    if not head:
        fail(f'{path.name}: start the file with a block of "key: value" lines between two --- lines')
    page = {}
    for line in head.group(1).splitlines():
        if not line.strip():
            continue
        key, colon, value = line.partition(':')
        key = key.strip()
        if not colon or key not in REQUIRED + OPTIONAL:
            fail(f'{path.name}: unknown line "{line}", allowed keys are {", ".join(REQUIRED + OPTIONAL)}')
        page[key] = value.strip()
    missing = [key for key in REQUIRED if not page.get(key)]
    if missing:
        fail(f'{path.name}: missing {", ".join(missing)}')
    for key in ('updated', 'expires'):
        try:
            if page.get(key):
                page[key + '_date'] = date.fromisoformat(page[key])
        except ValueError:
            fail(f'{path.name}: write {key} as YYYY-MM-DD')
    if slug == HUB:
        fail(f'{path.name}: {HUB} is the overview page that build.sh writes, pick another slug')
    if page.get('image'):
        if not page.get('image-alt'):
            fail(f'{path.name}: add image-alt, a short description of the share image')
        size = image_size(ROOT / page['image'].split('?')[0].lstrip('/'))
        if size != SHARE_SIZE:
            fail(f'{path.name}: the share image must be {SHARE_SIZE[0]}x{SHARE_SIZE[1]} px, {page["image"]} is {size[0]}x{size[1]}')
    url_path = f'/{slug}/' if lang == 'en' else f'/de/{slug}/'
    page.update(
        slug=slug,
        lang=lang,
        source=f'_pages/{path.name}',
        url=SITE + url_path,
        out=ROOT / url_path.strip('/') / 'index.html',
        body=text[head.end():].strip(),
    )
    return page


def image_size(path):
    """Width and height of a PNG or WebP file."""
    if not path.exists():
        fail(f'{path.relative_to(ROOT)} does not exist')
    data = path.read_bytes()[:40]
    if data[:8] == b'\x89PNG\r\n\x1a\n':
        return int.from_bytes(data[16:20], 'big'), int.from_bytes(data[20:24], 'big')
    if data[:4] == b'RIFF' and data[8:12] == b'WEBP':
        kind = data[12:16]
        if kind == b'VP8X':
            return int.from_bytes(data[24:27], 'little') + 1, int.from_bytes(data[27:30], 'little') + 1
        if kind == b'VP8 ':
            return int.from_bytes(data[26:28], 'little') & 0x3fff, int.from_bytes(data[28:30], 'little') & 0x3fff
        if kind == b'VP8L':
            bits = int.from_bytes(data[21:25], 'little')
            return (bits & 0x3fff) + 1, ((bits >> 14) & 0x3fff) + 1
    fail(f'{path.relative_to(ROOT)}: use a PNG or WebP file for the share image')


def link_cards(pages):
    cards = ''.join(
        f'    <a href="{p["url"][len(SITE):]}"><b>{html.escape(p["title"])}</b><span>{html.escape(p["description"])}</span></a>\n'
        for p in pages
    )
    return f'  <div class="hub">\n{cards}  </div>'


def hub_page(lang, pages, t):
    """The /resources/ page, with every page of one language grouped by topic."""
    own = [p for p in pages if p['lang'] == lang]
    topics = {}
    for p in sorted(own, key=lambda p: p['title'].lower()):
        topics.setdefault(p.get('topic') or t['default_topic'], []).append(p)
    sections = [
        f'<section class="page-section">\n  <div class="section-head">\n    <h2>{html.escape(topic)}</h2>\n  </div>\n{link_cards(items)}\n</section>'
        for topic, items in sorted(topics.items())
    ]
    url_path = f'/{HUB}/' if lang == 'en' else f'/de/{HUB}/'
    return {
        'slug': HUB,
        'lang': lang,
        'source': HUB_SOURCE,
        'title': t['resources_title'],
        'description': t['resources_description'],
        'updated': max((p['updated'] for p in own), default=date.today().isoformat()),
        'url': SITE + url_path,
        'out': ROOT / url_path.strip('/') / 'index.html',
        'body': '\n\n'.join(sections) or f'<p>{html.escape(t["resources_empty"])}</p>',
        'hub': True,
    }


def related(page, pages, t):
    """Up to four other pages of the same language, the same topic first."""
    others = [p for p in pages.values() if p['lang'] == page['lang'] and p['slug'] != page['slug'] and not p.get('hub')]
    others.sort(key=lambda p: (p.get('topic') != page.get('topic'), p['title'].lower()))
    if page.get('hub') or not others:
        return ''
    return (
        f'  <section class="wrap page-body page-related">\n    <div class="section-head">\n      <h2>{html.escape(t["related"])}</h2>\n    </div>\n'
        f'{link_cards(others[:4])}\n    <p class="page-related-all"><a href="{t["resources_url"]}">{html.escape(t["all_resources"])}</a></p>\n  </section>'
    )


def read_components():
    components = {}
    for path in sorted((PAGES / '_components').glob('*.html')):
        components[path.stem] = re.sub(r'^\s*<!--.*?-->\s*', '', path.read_text(), count=1, flags=re.S).rstrip()
    return components


def expand(body, components, source):
    """Replaces every <x-name attr="..."> ... </x-name> with _pages/_components/name.html."""

    def fill(match):
        name, attr_text, content = match.group(1), match.group(2), match.group(3)
        if name not in components:
            fail(f'{source}: unknown component <x-{name}>, there is {", ".join("<x-" + n + ">" for n in components)}')
        template = components[name]
        values = dict(re.findall(r'([a-z-]+)="([^"]*)"', attr_text))
        values['content'] = (content or '').strip()
        wanted = set(re.findall(r'\{\{([a-z-]+)\}\}', template))
        missing = sorted(wanted - set(values))
        unknown = sorted(set(values) - wanted - {'content'})
        if missing or unknown:
            fail(f'{source}: <x-{name}> needs {", ".join(sorted(wanted - {"content"})) or "no attributes"}'
                 + (f', missing {", ".join(missing)}' if missing else '')
                 + (f', unknown {", ".join(unknown)}' if unknown else ''))
        if content and 'content' not in wanted:
            fail(f'{source}: <x-{name}> takes no content, close it with />')
        return re.sub(r'\{\{([a-z-]+)\}\}', lambda m: values[m.group(1)], template)

    for _ in range(50):
        body, count = COMPONENT_RE.subn(fill, body)
        if not count:
            break
    if '<x-' in body:
        fail(f'{source}: a component tag is not closed')
    return body


class TextMaker(HTMLParser):
    """Turns page HTML into Markdown-like plain text for llms-full.txt."""

    BLOCKS = {'p', 'div', 'section', 'details', 'ul', 'ol', 'table', 'tr', 'figure'}
    # Each page sits under a ### heading in llms-full.txt, so its own headings start at ####.
    EMPTY = {'br', 'img', 'hr', 'input', 'source', 'meta', 'link', 'wbr'}
    HEADINGS = {'h2': '#### ', 'h3': '##### ', 'h4': '###### ', 'summary': '##### '}

    def __init__(self):
        super().__init__()
        self.parts = []
        self.links = []
        self.skip = 0

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if self.skip and tag in self.EMPTY:
            return
        if self.skip or tag in ('script', 'style', 'button') or 'hidden' in attrs:
            self.skip += 1
        elif tag in self.HEADINGS:
            self.parts.append('\n\n' + self.HEADINGS[tag])
        elif tag in self.BLOCKS:
            self.parts.append('\n\n')
        elif tag == 'li':
            self.parts.append('\n- ')
        elif tag == 'br':
            self.parts.append('\n')
        elif tag == 'a':
            href = attrs.get('href', '')
            self.links.append(SITE + href if href.startswith('/') else href)
            self.parts.append('[')

    def handle_startendtag(self, tag, attrs):
        if not self.skip:
            self.handle_starttag(tag, attrs)

    def handle_endtag(self, tag):
        if tag in self.EMPTY:
            return
        if self.skip:
            self.skip -= 1
        elif tag in self.HEADINGS or tag in self.BLOCKS:
            self.parts.append('\n\n')
        elif tag == 'a':
            self.parts.append(f']({self.links.pop()})')

    def handle_data(self, data):
        if not self.skip:
            self.parts.append(re.sub(r'\s+', ' ', data))

    def text(self):
        lines = [line.strip() for line in ''.join(self.parts).split('\n')]
        return re.sub(r'\n{3,}', '\n\n', '\n'.join(lines)).strip()


def plain_text(fragment):
    maker = TextMaker()
    maker.feed(fragment)
    maker.close()
    return maker.text()


def questions(body):
    found = re.findall(r'<details class="faq-item"[^>]*>\s*<summary>(.*?)</summary>(.*?)</details>', body, re.S)
    return [(plain_text(q), plain_text(a)) for q, a in found]


def structured_data(page):
    graph = [
        {
            '@type': 'WebPage',
            '@id': page['url'] + '#page',
            'url': page['url'],
            'name': page['title'],
            'description': page['description'],
            'inLanguage': page['lang'],
            'dateModified': page['updated'],
            'about': {'@id': SITE + '/#app'},
        },
        {
            '@type': 'SoftwareApplication',
            '@id': SITE + '/#app',
            'name': 'Sightline',
            'operatingSystem': 'macOS 14 or later',
            'applicationCategory': 'UtilitiesApplication',
            'url': SITE + '/',
            'downloadUrl': 'https://apps.apple.com/app/sightline/id6812521593',
        },
    ]
    faq = questions(page['body'])
    if faq:
        graph.append({
            '@type': 'FAQPage',
            '@id': page['url'] + '#faq',
            'mainEntity': [
                {'@type': 'Question', 'name': q, 'acceptedAnswer': {'@type': 'Answer', 'text': a}}
                for q, a in faq
            ],
        })
    data = json.dumps({'@context': 'https://schema.org', '@graph': graph}, ensure_ascii=False, indent=2)
    return data.replace('</', '<\\/')


def render(page, pages, layout, strings):
    t = strings[page['lang']]
    other_lang = 'de' if page['lang'] == 'en' else 'en'
    other = pages.get((page['slug'], other_lang))
    alternates = ''
    language_redirect = ''
    if other:
        en_url = page['url'] if page['lang'] == 'en' else other['url']
        de_url = other['url'] if page['lang'] == 'en' else page['url']
        alternates = '\n'.join([
            f'  <link rel="alternate" hreflang="en" href="{en_url}">',
            f'  <link rel="alternate" hreflang="de" href="{de_url}">',
            f'  <link rel="alternate" hreflang="x-default" href="{en_url}">',
        ])
        if page['lang'] == 'en':
            language_redirect = (
                "  <script>\n"
                "    try {\n"
                "      var preferred = (navigator.languages || [navigator.language]).map(function (l) { return l.slice(0, 2).toLowerCase(); }).filter(function (l) { return l === 'en' || l === 'de'; })[0];\n"
                f"      if (!localStorage.getItem('sightline-lang') && preferred === 'de') location.replace('{de_url[len(SITE):]}' + location.hash);\n"
                "    } catch (e) {}\n"
                "  </script>"
            )
    other_url = other['url'][len(SITE):] if other else strings[other_lang]['home_url']
    expiry_redirect = ''
    if page.get('expires'):
        day_after = (page['expires_date'] + timedelta(days=1)).isoformat()
        expiry_redirect = f"  <script>if (Date.now() >= new Date('{day_after}T00:00:00').getTime()) location.replace('{t['home_url']}');</script>"
    eyebrow = page.get('eyebrow')
    image = SITE + page['image'] if page.get('image', '').startswith('/') else page.get('image') or t['share_image']
    values = {
        'image': image,
        'image_alt': html.escape(page.get('image-alt') or t['share_image_alt']),
        'locale_alternate': f'  <meta property="og:locale:alternate" content="{strings[other_lang]["locale"]}">' if other else '',
        'related': related(page, pages, t),
        'mark': MARK.format(page['source']),
        'lang': page['lang'],
        'title': html.escape(page['title']),
        'description': html.escape(page['description']),
        'lead': html.escape(page.get('lead') or page['description']),
        'url': page['url'],
        'alternates': alternates,
        'language_redirect': language_redirect,
        'expiry_redirect': expiry_redirect,
        'structured_data': structured_data(page),
        'eyebrow': f'<p class="eyebrow">{html.escape(eyebrow)}</p>' if eyebrow else '',
        'body': page['body'],
        'other_lang': other_lang,
        'other_url': other_url,
        **{f't.{key}': value for key, value in t.items()},
    }

    def fill(match):
        key = match.group(1)
        if key not in values:
            fail(f'_pages/_layout.html: unknown placeholder {{{{{key}}}}}')
        return values[key]

    filled = re.sub(r'\{\{([\w.]+)\}\}', fill, layout)
    return re.sub(r'\n\s*\n(\s*\n)+', '\n\n', filled).replace('\n\n  <', '\n  <')


def write_if_changed(path, text):
    if not path.exists() or path.read_text() != text:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print('wrote', path.relative_to(ROOT))


def build_pages(styles):
    layout = (PAGES / '_layout.html').read_text()
    strings = json.loads((PAGES / '_strings.json').read_text())
    components = read_components()
    pages = {}
    for path in sorted(PAGES.glob('*.html')):
        if path.name.startswith('_'):
            continue
        page = read_page(path)
        if page.get('expires') and page['expires_date'] < date.today():
            print(f'skipped {page["source"]}, it expired on {page["expires"]}')
            continue
        if 'class="' in page['body']:
            print(f'note: {page["source"]} uses its own class names, prefer a component from _pages/_components')
        page['body'] = expand(page['body'], components, page['source'])
        pages[(page['slug'], page['lang'])] = page
    listed = list(pages.values())
    for lang in LANGS:
        hub = hub_page(lang, listed, strings[lang])
        pages[(HUB, lang)] = hub

    for page in pages.values():
        out = page['out']
        if out.exists():
            mark = MARK_RE.search(out.read_text())
            if not mark or mark.group(1) != page['source']:
                fail(f'{page["source"]}: {out.relative_to(ROOT)} already exists and was not made from this file, pick another slug')
        elif out.parent.exists():
            fail(f'{page["source"]}: the folder {out.parent.relative_to(ROOT)} already exists, pick another slug')
        write_if_changed(out, with_styles(render(page, pages, layout, strings), styles, page['source']))

    sources = {page['source'] for page in pages.values()}
    for path in list(ROOT.glob('*/index.html')) + list(ROOT.glob('de/*/index.html')):
        mark = MARK_RE.search(path.read_text())
        if mark and mark.group(1) not in sources:
            path.unlink()
            print('removed', path.relative_to(ROOT))
            if not any(path.parent.iterdir()):
                path.parent.rmdir()
    return sorted(pages.values(), key=lambda p: (p['slug'], LANGS.index(p['lang'])))


def replace_block(path, start, end, block, insert_before):
    text = path.read_text()
    pattern = re.compile(re.escape(start) + r'.*?' + re.escape(end) + r'\n', re.S)
    new_block = f'{start}\n{block}{end}\n' if block else ''
    if pattern.search(text):
        updated = pattern.sub(lambda _: new_block, text, count=1)
    elif not new_block:
        updated = text
    elif insert_before is None:
        updated = text.rstrip('\n') + '\n\n' + new_block
    else:
        if insert_before not in text:
            fail(f'{path.name}: could not find where to put the pages')
        spacing = '' if new_block.startswith('  <') else '\n'
        updated = text.replace(insert_before, new_block + spacing + insert_before, 1)
    write_if_changed(path, updated)


def update_sitemap(pages):
    entries = []
    for page in pages:
        lines = ['  <url>', f'    <loc>{page["url"]}</loc>', f'    <lastmod>{page["updated"]}</lastmod>']
        pair = [p for p in pages if p['slug'] == page['slug']]
        if len(pair) == 2:
            for p in pair:
                lines.append(f'    <xhtml:link rel="alternate" hreflang="{p["lang"]}" href="{p["url"]}"/>')
        lines.append('  </url>')
        entries.append('\n'.join(lines) + '\n')
    replace_block(ROOT / 'sitemap.xml', '  <!-- pages from _pages/, written by build.sh -->', '  <!-- end pages -->', ''.join(entries), '</urlset>')


def update_llms(pages):
    english = {p['slug'] for p in pages if p['lang'] == 'en'}
    listed = [p for p in pages if p['lang'] == 'en' or p['slug'] not in english]
    links = ''.join(f'- [{p["title"]}]({p["url"]}): {p["description"]}\n' for p in listed)
    replace_block(ROOT / 'llms.txt', '## Pages', '<!-- end pages -->', '\n' + links + '\n' if links else '', '## Optional')
    full = ''.join(
        f'\n### {p["title"]}\n\n{p["url"]}, updated {p["updated"]}\n\n{p["description"]}\n\n{plain_text(p["body"])}\n\n'
        for p in listed
    )
    replace_block(ROOT / 'llms-full.txt', '## Pages', '<!-- end pages -->', full, None)


STYLES_START = '  <!-- inlined from styles.css, run build.sh after editing it -->'
STYLES_END = '  <!-- end styles.css -->'
STYLES_TARGET = re.compile(re.escape(STYLES_START) + r'.*?' + re.escape(STYLES_END) + r'|  <link rel="stylesheet" href="styles\.css">', re.S)


def read_styles():
    css = (ROOT / 'styles.css').read_text().strip()
    return f'{STYLES_START}\n  <style>\n{css}\n  </style>\n{STYLES_END}'


def with_styles(text, styles, name):
    updated, count = STYLES_TARGET.subn(lambda _: styles, text, count=1)
    if count != 1:
        fail(f'{name}: no stylesheet link or inlined block found')
    return updated


def inline_styles(styles):
    pages = sorted(ROOT.glob('*.html')) + sorted(ROOT.glob('*/index.html')) + sorted(ROOT.glob('de/*/index.html')) + sorted(ROOT.glob('docs/*/index.html'))
    for page in pages:
        write_if_changed(page, with_styles(page.read_text(), styles, page.relative_to(ROOT)))


def update_gitignore(pages):
    """Keeps the built pages out of git. The GitHub Action builds them on every deploy."""
    lines = ''.join(f'/{p["out"].parent.relative_to(ROOT).as_posix()}/\n' for p in pages)
    replace_block(ROOT / '.gitignore', '# pages built from _pages/ by build.sh', '# end pages', lines, None)


def check_listed():
    """Warns about pages that search engines and AI tools can't find, or that look bare when shared."""
    sitemap = (ROOT / 'sitemap.xml').read_text()
    llms = (ROOT / 'llms.txt').read_text()
    pages = sorted(ROOT.glob('*.html')) + sorted(ROOT.glob('*/index.html')) + sorted(ROOT.glob('de/*/index.html')) + sorted(ROOT.glob('docs/*/index.html'))
    for page in pages:
        text = page.read_text()
        path = page.relative_to(ROOT).as_posix()
        missing = [tag.split('"')[1] for tag in SHARE_TAGS if tag not in text]
        if missing:
            print(f'warning: {path} is missing share data: {", ".join(missing)}')
        if re.search(r'<meta name="robots" content="[^"]*noindex', text):
            continue
        url = f'{SITE}/{path.removesuffix("index.html")}'
        if f'<loc>{url}</loc>' not in sitemap:
            print(f'warning: {path} is missing from sitemap.xml')
        if not path.startswith('de/') and f']({url})' not in llms:
            print(f'warning: {path} is missing from llms.txt, add a link with a one-line summary')


if __name__ == '__main__':
    styles = read_styles()
    pages = build_pages(styles)
    update_sitemap(pages)
    update_llms(pages)
    update_gitignore(pages)
    inline_styles(styles)
    check_listed()
